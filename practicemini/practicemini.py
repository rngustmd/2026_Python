import numpy as np
# 데이터 불러오기
data = np.genfromtxt( './practicemini/국민건강보험공단_직역별 성별 연령별 건강검진정보_20231231.csv', delimiter=',', skip_header=1, encoding='cp949', dtype=str, autostrip=True )
# 2023년 데이터만 추출
data = data[ data[ : , 0 ] == '2023' ] 
# 고혈압 의심 인원이 빈칸인 행 제외
data = data[ data[ : , 27] != '']
# 수검인원 1,000명 이상인 집단만 추출 (추가)
data = data[ data[ : , 5 ].astype( float ) >= 1000 ]
줄번호 = np.arange(len(data)) + 2
# 숫자형으로 변환
target = data[ : , 4 ].astype( float )
exam = data[ : , 5 ].astype( float )
hypertension = data[ : , 27 ].astype( float )
print("분석 집단 수:", len( data ) )

# [ Step 1 ] 고혈압 질환 의심 인원 현황 분석
# 2023년 집단별 고혈압 질환 의심 인원의 평균값과 최댓값
의심인원 = data[:, 27]
print("평균 고혈압 질환 의심 인원:", np.mean(의심인원))
print("최대 고혈압 질환 의심 인원:", np.max(의심인원))
print("최댓값 집단 ID(엑셀 줄):", 줄번호[np.argmax(의심인원)])

# [ Step 2 ] 고혈압 우선관리 집단 선별
# 고혈압 질환 의심률이 일정 수치 이상이거나 고혈압 질환 의심 인원이 일정 수치 이상인 집단을 추출
의심률 = data[:, 27] / data[:, 5] * 100
print("의심률 평균:", np.mean(의심률), "%")
print("의심 인원 평균:", np.mean(의심인원), "명")
우선관리조건 = (의심률 >= np.mean(의심률)) | (의심인원 >= np.mean(의심인원))
우선관리집단 = 줄번호[우선관리조건]
print("우선관리 집단 ID:", 우선관리집단)
print("우선관리 집단 수:", len(우선관리집단))

# [ Step 3 ] 집단별 고혈압 집중 관리 지수 분석
# 고혈압 질환 의심 인원을 수검인원으로 나누어 집단별 집중 관리 지수를 산출하고, 가장 높은 집단 찾기

# [ Step 4 ] 고혈압 의심률과 건강검진 참여율을 고려한 복합 취약 집단 분석 
# 고혈압 질환 의심률이 일정 수치 이상이면서 건강검진 참여율이 일정 수치 미만인 집단을 추출하고, 전체 집단에서 차지하는 비율을 구한다. 
고혈압의심률 = ( hypertension / exam ) * 100
건강검진참여율 = ( exam / target ) * 100
취약집단 = ( 고혈압의심률 >= 10 ) & ( 건강검진참여율 < 70 )
print( np.sum( 취약집단 ) )
print( np.mean( 취약집단 ) * 100 )

# [ Step 5 ] 미수검자 규모를 고려한 최우선 건강검진 지원 집단 선정 
# Step 4에서 추출한 집단을 대상으로 미수검자 수와 고혈압 의심률을 활용해 검진 우선순위 참고지표를 산출한다. 
# 해당 지표를 Min-Max Scaling으로 정규화하고, 0.9 이상인 집단을 최우선 지원 집단으로 선정한다. 
취약집단데이터 = data[ 취약집단 ]
미검수자 = ( target - exam )[ 취약집단 ]
취약집단의심률 = 고혈압의심률[ 취약집단 ]
우선순위지표 = 미검수자 * ( 취약집단의심률 / 100 )
정규화점수 = ( 우선순위지표 - np.min( 우선순위지표 ) ) / ( np.max( 우선순위지표 ) - np.min( 우선순위지표 ) )
최우선집단 = 취약집단데이터[ 정규화점수 >= 0.9 ]
print( len(최우선집단) )
print( 최우선집단[ : , 1:4 ] )
print( 정규화점수[ 정규화점수 >= 0.9 ] )

